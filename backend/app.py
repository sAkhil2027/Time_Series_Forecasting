@app.get("/api/history")
def api_history(store_id: int = Query(1, ge=1, le=10), item_id: int = Query(1, ge=1, le=50), days: int = Query(90, ge=30, le=365)):
    """Fetch historical sales sequence for store and item."""
    try:
        history = get_store_item_history(store_id, item_id, days)
        return {"store_id": store_id, "item_id": item_id, "days": days, "data": history}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/forecast")
def api_forecast(req: ForecastRequest):
    """Generates future sales forecast for selected store, item, and model architecture."""
    try:
        result = run_forecast(req.store_id, req.item_id, req.model_name, req.horizon)
        return result
    except FileNotFoundError as fnf:
        raise HTTPException(status_code=503, detail=f"Model not ready: {str(fnf)}")
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/compare")
def api_compare(req: CompareRequest):
    """Compares forecasts generated by all 4 deep learning models."""
    try:
        results = compare_all_models(req.store_id, req.item_id, req.horizon)
        return {
            "store_id": req.store_id,
            "item_id": req.item_id,
            "horizon": req.horizon,
            "comparisons": results
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/forecast-custom")
def api_forecast_custom(req: CustomForecastRequest):
    """Forecast future values from custom sequence array."""
    try:
        result = forecast_custom_sequence(req.values, req.model_name, req.horizon)
        return result
    except Exception as e:
        raise HTTPException(status_code=400, detail=str(e))

@app.post("/api/upload-csv")
async def api_upload_csv(file: UploadFile = File(...), model_name: str = "LSTM", horizon: int = 30):
    """Upload CSV containing 'sales' column to run immediate deep learning forecast."""
    try:
        content = await file.read()
        df = pd.read_csv(io.BytesIO(content))
        # Look for a numeric column named 'sales' or take the first numeric column
        target_col = None
        for col in df.columns:
            if 'sale' in col.lower():
                target_col = col
                break
        if target_col is None:
            numeric_cols = df.select_dtypes(include=['number']).columns
            if len(numeric_cols) > 0:
                target_col = numeric_cols[0]
            else:
                raise ValueError("No numeric data column found in the uploaded CSV.")

        vals = df[target_col].dropna().tolist()
        if len(vals) < 30:
            raise ValueError(f"CSV must contain at least 30 data points, found {len(vals)}.")

        result = forecast_custom_sequence(vals, model_name, horizon)
        return {
            "filename": file.filename,
            "detected_column": target_col,
            "input_points_count": len(vals),
            "result": result
        }
    except Exception as e:
        raise HTTPException(status_code=400, detail=str(e))

