import os
import io
from typing import Optional, List
from fastapi import FastAPI, Query, HTTPException, UploadFile, File
from fastapi.staticfiles import StaticFiles
from fastapi.responses import FileResponse, JSONResponse
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from contextlib import asynccontextmanager
import pandas as pd

from backend.inference import (
    get_metrics,
    get_data,
    load_model_cached,
    get_store_item_history,
    run_forecast,
    compare_all_models,
    forecast_custom_sequence
)

@asynccontextmanager
async def lifespan(app: FastAPI):
    print("[Startup] Initializing Time Series Forecasting Engine...")
    try:
        get_metrics()
        get_data()
        load_model_cached("LSTM")
        print("[Startup] Caches and default neural model initialized successfully.")
    except Exception as e:
        print(f"[Startup Warning] Model/Data preloading notice: {e}")
    yield
    print("[Shutdown] Shutting down Time Series Forecasting Engine.")

app = FastAPI(
    title="Deep Learning Time Series Forecasting API",
    description="Interactive forecasting API comparing MLP, CNN, LSTM, and CNN-LSTM models on store item demand.",
    version="1.0.0",
    lifespan=lifespan
)

# Enable CORS for external frontend or development flexibility
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATIC_DIR = os.path.join(BASE_DIR, 'static')
os.makedirs(STATIC_DIR, exist_ok=True)

class ForecastRequest(BaseModel):
    store_id: int = 1
    item_id: int = 1
    model_name: str = "LSTM"
    horizon: int = 30

class CompareRequest(BaseModel):
    store_id: int = 1
    item_id: int = 1
    horizon: int = 30

class CustomForecastRequest(BaseModel):
    values: List[float]
    model_name: str = "LSTM"
    horizon: int = 30

